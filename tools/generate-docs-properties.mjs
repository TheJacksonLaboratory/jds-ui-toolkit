#!/usr/bin/env node
/**
 * Generates the component Properties table data from source-of-truth JSDoc.
 *
 * Runs Compodoc over libs/components to emit a documentation.json, then
 * extracts each component's inputs/outputs into a typed TS map that the docs
 * viewer imports. Regenerate with `pnpm docs:properties` whenever a
 * component's inputs/outputs or their JSDoc change.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const TSCONFIG = 'libs/components/tsconfig.lib.json';
const OUT_FILE =
  'apps/demo/src/app/docs-shell/generated/component-properties.generated.ts';

const tmp = mkdtempSync(join(tmpdir(), 'compodoc-'));

try {
  execFileSync(
    'npx',
    ['compodoc', '-p', TSCONFIG, '-e', 'json', '-d', tmp, '--silent'],
    { stdio: 'inherit' }
  );

  const doc = JSON.parse(readFileSync(join(tmp, 'documentation.json'), 'utf8'));

  // Compodoc renders JSDoc descriptions to HTML; flatten back to plain text.
  const stripHtml = (s) =>
    (s || '')
      .replace(/<[^>]+>/g, '')
      .replace(/\s+/g, ' ')
      .trim();

  const toProp = (p) => ({
    name: p.name,
    type: p.type || 'unknown',
    default: p.defaultValue || undefined,
    required: Boolean(p.required),
    description: stripHtml(p.description),
  });

  const map = {};
  for (const c of doc.components || []) {
    map[c.name] = {
      inputs: (c.inputsClass || []).map(toProp),
      outputs: (c.outputsClass || []).map((o) => ({
        name: o.name,
        type: o.type || o.defaultValue || 'EventEmitter',
        required: false,
        description: stripHtml(o.description),
      })),
    };
  }

  const banner =
    '// GENERATED by tools/generate-docs-properties.mjs — do not edit.\n' +
    '// Source of truth: JSDoc + inputs/outputs in libs/components.\n' +
    "// Regenerate with `pnpm docs:properties`.\n";

  const body =
    "import { ApiDoc } from '@jax-data-science/component-docs';\n\n" +
    'export const COMPONENT_PROPERTIES: Record<string, ApiDoc> = ' +
    JSON.stringify(map, null, 2) +
    ';\n';

  writeFileSync(OUT_FILE, banner + '\n' + body);
  console.log(`Wrote ${OUT_FILE} (${Object.keys(map).length} components)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
