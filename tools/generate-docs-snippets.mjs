#!/usr/bin/env node
/**
 * Generates variation code snippets from the live demo templates.
 *
 * Scans every showcase template for `snippet:<id>` / `/snippet` marker
 * comments and extracts the markup between them into a typed map keyed by
 * component slug then variation id. Because the extracted markup is the exact
 * template that renders the live demo, the code block cannot drift.
 * Regenerate with `pnpm docs:snippets`.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const PAGES_DIR = 'apps/demo/src/app/components/pages';
const OUT_FILE =
  'apps/demo/src/app/docs-shell/generated/component-snippets.generated.ts';

const SNIPPET_RE =
  /<!--\s*snippet:([\w-]+)\s*-->([\s\S]*?)<!--\s*\/snippet\s*-->/g;

/** Remove common leading indentation and surrounding blank lines. */
function dedent(text) {
  const lines = text.replace(/^\n+|\s+$/g, '').split('\n');
  const indents = lines
    .filter((l) => l.trim())
    .map((l) => l.match(/^\s*/)[0].length);
  const min = indents.length ? Math.min(...indents) : 0;
  return lines.map((l) => l.slice(min)).join('\n');
}

const map = {};
for (const dir of readdirSync(PAGES_DIR, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const slug = dir.name;
  let html;
  try {
    html = readFileSync(join(PAGES_DIR, slug, `showcase-${slug}.component.html`), 'utf8');
  } catch {
    continue; // no showcase template for this page
  }
  for (const m of html.matchAll(SNIPPET_RE)) {
    const [, id, body] = m;
    (map[slug] ??= {})[id] = dedent(body);
  }
}

const banner =
  '// GENERATED by tools/generate-docs-snippets.mjs — do not edit.\n' +
  '// Source of truth: `snippet:<id>` markers in showcase demo templates.\n' +
  "// Regenerate with `pnpm docs:snippets`.\n";

const body =
  'export const COMPONENT_SNIPPETS: Record<string, Record<string, string>> = ' +
  JSON.stringify(map, null, 2) +
  ';\n';

writeFileSync(OUT_FILE, banner + '\n' + body);
const total = Object.values(map).reduce((n, s) => n + Object.keys(s).length, 0);
console.log(`Wrote ${OUT_FILE} (${total} snippets across ${Object.keys(map).length} components)`);

void basename; // reserved for future per-file diagnostics
